class SyntheticMCQGenerator:
    """Generates synthetic examination documents with ground-truth graphs."""

    def __init__(
        self,
        output_dir: str = "training/datasets/SETU-SR/synthetic",
        seed: int = 42
    ):
        self.output_dir = output_dir
        self.img_dir = os.path.join(output_dir, "images")
        self.ann_dir = os.path.join(output_dir, "annotations")
        self.seed = seed
        random.seed(seed)
        
        os.makedirs(self.img_dir, exist_ok=True)
        os.makedirs(self.ann_dir, exist_ok=True)

        # Fonts configuration
        font_dir = "C:/Windows/Fonts"
        self.font_families = [
            os.path.join(font_dir, "arial.ttf"),
            os.path.join(font_dir, "calibri.ttf"),
            os.path.join(font_dir, "times.ttf")
        ]
        # Fallback to Arial if others missing
        self.font_families = [f for f in self.font_families if os.path.exists(f)]
        if not self.font_families:
            self.font_families = ["arial.ttf"]

    def _get_font(self, family: str, size: int) -> ImageFont.FreeTypeFont:
        try:
            return ImageFont.truetype(family, size)
        except Exception:
            return ImageFont.load_default()

    def generate_dataset(self, num_documents: int = 250) -> Tuple[List[Dict[str, Any]], Dict[str, int]]:
        all_edges: List[Dict[str, Any]] = []
        global_stats = {"PARENT_OF": 0, "OPTION_OF": 0, "CONTINUATION_OF": 0, "NONE": 0}
        manifest_docs = []

        print(f"Starting procedural generation of {num_documents} exam documents (Seed={self.seed})...")

        for doc_idx in range(1, num_documents + 1):
            doc_seed = self.seed + doc_idx * 17
            doc_edges, doc_meta = self._generate_single_document(doc_idx, doc_seed)
            all_edges.extend(doc_edges)
            manifest_docs.append(doc_meta)

            for e in doc_edges:
                global_stats[e["relationship_label"]] += 1

            if doc_idx % 25 == 0 or doc_idx == num_documents:
                print(f"  Generated {doc_idx}/{num_documents} documents | Cumulative Edges: {len(all_edges)} | {global_stats}")

        # Save synthetic edges jsonl
        out_jsonl = os.path.join(self.output_dir, "synthetic_edges.jsonl")
        with open(out_jsonl, "w", encoding="utf-8") as fp:
            for e in all_edges:
                fp.write(json.dumps(e) + "\n")

        # Save manifest
        manifest_path = os.path.join(self.output_dir, "synthetic_manifest.json")
        with open(manifest_path, "w", encoding="utf-8") as fp:
            json.dump({
                "total_documents": num_documents,
                "total_edges": len(all_edges),
                "class_distribution": global_stats,
                "documents": manifest_docs
            }, fp, indent=2)

        print(f"Synthetic generation complete: {len(all_edges)} edges saved to {out_jsonl}")
        return all_edges, global_stats

    def _generate_single_document(self, doc_idx: int, doc_seed: int) -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:
        rng = random.Random(doc_seed)
        
        # Dimensions: A4-like canvas (width 1200, height 1600)
        page_w = 1200
        page_h = 1600
        num_columns = 1 if doc_idx <= 150 else 2  # 150 single-column, 100 double-column
        num_pages = 2 if (doc_idx % 5 == 0) else 1  # 50 two-page documents
        
        font_family = rng.choice(self.font_families)
        title_font = self._get_font(font_family, rng.randint(22, 26))
        section_font = self._get_font(font_family, rng.randint(16, 18))
        q_font = self._get_font(font_family, rng.randint(13, 15))
        opt_font = self._get_font(font_family, rng.randint(12, 14))
        code_font = self._get_font(font_family, 12)

        doc_id = f"synth_{doc_idx:04d}"
        doc_edges: List[Dict[str, Any]] = []
        doc_pages_meta = []

        # Generate each page
        q_counter = 1
        for page_num in range(1, num_pages + 1):
            page_id = f"{doc_id}_p{page_num}"
            img = Image.new("RGB", (page_w, page_h), color=(255, 255, 255))
            draw = ImageDraw.Draw(img)

            blocks: List[Dict[str, Any]] = []
            block_id = 1

            margin_x = 60
            margin_y = 60
            usable_w = page_w - 2 * margin_x
            usable_h = page_h - 2 * margin_y

            current_y = margin_y

            # Page Header on Page 1
            if page_num == 1:
                title_text = rng.choice(EXAM_TITLES)
                bbox_t = draw.textbbox((margin_x, current_y), title_text, font=title_font)
                draw.text((margin_x, current_y), title_text, fill=(10, 10, 10), font=title_font)
                blocks.append({
                    "block_id": block_id,
                    "block_type": "TITLE",
                    "text": title_text,
                    "bbox": [float(v) for v in bbox_t],
                    "page_num": page_num
                })
                header_block_id = block_id
                block_id += 1
                current_y = bbox_t[3] + rng.randint(15, 25)

                # Section Header
                sec_text = rng.choice(SECTION_TITLES)
                bbox_s = draw.textbbox((margin_x, current_y), sec_text, font=section_font)
                draw.text((margin_x, current_y), sec_text, fill=(40, 40, 40), font=section_font)
                blocks.append({
                    "block_id": block_id,
                    "block_type": "HEADING",
                    "text": sec_text,
                    "bbox": [float(v) for v in bbox_s],
                    "page_num": page_num
                })
                sec_block_id = block_id
                block_id += 1
                current_y = bbox_s[3] + rng.randint(20, 30)
            else:
                sec_text = f"CONTINUED: {rng.choice(SECTION_TITLES)}"
                bbox_s = draw.textbbox((margin_x, current_y), sec_text, font=section_font)
                draw.text((margin_x, current_y), sec_text, fill=(40, 40, 40), font=section_font)
                blocks.append({
                    "block_id": block_id,
                    "block_type": "HEADING",
                    "text": sec_text,
                    "bbox": [float(v) for v in bbox_s],
                    "page_num": page_num
                })
                sec_block_id = block_id
                block_id += 1
                current_y = bbox_s[3] + rng.randint(15, 25)

            # Columns configuration
            col_width = (usable_w - 40) // 2 if num_columns == 2 else usable_w
            gutter = 40 if num_columns == 2 else 0

            # Render questions into columns
            questions_to_place = 4 if num_columns == 1 else 6
            col_y_cursors = [current_y, current_y]

            for col_idx in range(num_columns):
                col_left = margin_x + col_idx * (col_width + gutter)
                col_right = col_left + col_width

                col_q_count = questions_to_place // num_columns
                for _ in range(col_q_count):
                    if col_y_cursors[col_idx] > usable_h - 120:
                        break  # Page boundary

                    template = rng.choice(QUESTION_TEMPLATES)
                    q_num_str = f"Q{q_counter}. "
                    full_q_text = q_num_str + template["q"]
                    q_counter += 1

                    # Word wrap question text
                    wrapped_lines = self._wrap_text(full_q_text, q_font, col_width)
                    q_start_y = col_y_cursors[col_idx]
                    
                    # Draw question text
                    cur_y = q_start_y
                    line_boxes = []
                    for l in wrapped_lines:
                        l_box = draw.textbbox((col_left, cur_y), l, font=q_font)
                        draw.text((col_left, cur_y), l, fill=(15, 15, 15), font=q_font)
                        line_boxes.append(l_box)
                        cur_y = l_box[3] + 4

                    q_bbox = [
                        float(min(b[0] for b in line_boxes)),
                        float(min(b[1] for b in line_boxes)),
                        float(max(b[2] for b in line_boxes)),
                        float(max(b[3] for b in line_boxes))
                    ]
                    
                    q_block_id = block_id
                    blocks.append({
                        "block_id": q_block_id,
                        "block_type": "QUESTION",
                        "text": full_q_text,
                        "bbox": q_bbox,
                        "page_num": page_num
                    })
                    block_id += 1
                    cur_y += 8

                    # If template has embedded code, render code block
                    code_block_id = None
                    if template.get("has_code") and template.get("code"):
                        code_text = template["code"]
                        c_lines = code_text.split("\n")
                        c_boxes = []
                        c_y = cur_y
                        for cl in c_lines:
                            cb = draw.textbbox((col_left + 15, c_y), cl, font=code_font)
                            draw.text((col_left + 15, c_y), cl, fill=(30, 30, 80), font=code_font)
                            c_boxes.append(cb)
                            c_y = cb[3] + 3

                        code_bbox = [
                            float(min(b[0] for b in c_boxes) - 6),
                            float(min(b[1] for b in c_boxes) - 4),
                            float(max(b[2] for b in c_boxes) + 6),
                            float(max(b[3] for b in c_boxes) + 4)
                        ]
                        draw.rectangle(code_bbox, outline=(180, 180, 200), width=1)
                        code_block_id = block_id
                        blocks.append({
                            "block_id": code_block_id,
                            "block_type": "CODE",
                            "text": code_text,
                            "bbox": code_bbox,
                            "page_num": page_num
                        })
                        block_id += 1
                        cur_y = code_bbox[3] + 8

                    # Render Options
                    opt_labels = ["A", "B", "C", "D", "E"]
                    num_opts = rng.choice([2, 3, 4, 4, 4, 5])
                    opt_block_ids = []

                    opt_style = rng.choice(["bracket", "paren", "period"])
                    for opt_i in range(min(num_opts, len(template["options"]))):
                        lbl = opt_labels[opt_i]
                        prefix = f"[{lbl}] " if opt_style == "bracket" else (f"({lbl}) " if opt_style == "paren" else f"{lbl}. ")
                        opt_text = prefix + template["options"][opt_i]
                        
                        wrapped_opt = self._wrap_text(opt_text, opt_font, col_width - 20)
                        opt_boxes = []
                        for ol in wrapped_opt:
                            ob = draw.textbbox((col_left + 20, cur_y), ol, font=opt_font)
                            draw.text((col_left + 20, cur_y), ol, fill=(25, 25, 25), font=opt_font)
                            opt_boxes.append(ob)
                            cur_y = ob[3] + 4

                        opt_bbox = [
                            float(min(b[0] for b in opt_boxes)),
                            float(min(b[1] for b in opt_boxes)),
                            float(max(b[2] for b in opt_boxes)),
                            float(max(b[3] for b in opt_boxes))
                        ]
                        opt_id = block_id
                        blocks.append({
                            "block_id": opt_id,
                            "block_type": "OPTION",
                            "text": opt_text,
                            "bbox": opt_bbox,
                            "page_num": page_num
                        })
                        opt_block_ids.append(opt_id)
                        block_id += 1

                    # Update column vertical cursor
                    col_y_cursors[col_idx] = cur_y + rng.randint(18, 28)

            # Save rendered image
            img_filename = f"{doc_id}_p{page_num}.png"
            img_save_path = os.path.join(self.img_dir, img_filename)
            img.save(img_save_path, "PNG")

            # Extract ground-truth relational pairs for this page
            page_edges = self._extract_ground_truth_edges(
                blocks=blocks,
                doc_id=doc_id,
                page_id=page_id,
                page_w=page_w,
                page_h=page_h,
                provenance=f"synthetic/{img_filename}",
                rng=rng
            )
            doc_edges.extend(page_edges)

            # Save annotation json
            ann_filename = f"{doc_id}_p{page_num}.json"
            ann_save_path = os.path.join(self.ann_dir, ann_filename)
            with open(ann_save_path, "w", encoding="utf-8") as fp:
                json.dump({
                    "doc_id": doc_id,
                    "page_id": page_id,
                    "page_width": page_w,
                    "page_height": page_h,
                    "num_columns": num_columns,
                    "blocks": blocks,
                    "edges_count": len(page_edges)
                }, fp, indent=2)

            doc_pages_meta.append({
                "page_num": page_num,
                "blocks_count": len(blocks),
                "edges_count": len(page_edges),
                "image_path": img_save_path
            })

        return doc_edges, {
            "doc_id": doc_id,
            "num_pages": num_pages,
            "num_columns": num_columns,
            "total_edges": len(doc_edges),
            "pages": doc_pages_meta
        }

    def _extract_ground_truth_edges(
        self,
        blocks: List[Dict[str, Any]],
        doc_id: str,
        page_id: str,
        page_w: int,
        page_h: int,
        provenance: str,
        rng: random.Random
    ) -> List[Dict[str, Any]]:
        edges: List[Dict[str, Any]] = []
        block_map = {b["block_id"]: b for b in blocks}

        # 1. Establish structural groups
        # Find headings, questions, options, code blocks
        questions = [b for b in blocks if b["block_type"] == "QUESTION"]
        headings = [b for b in blocks if b["block_type"] in ("HEADING", "TITLE")]
        
        pos_pairs = set()

        # Rule 1: HEADING -> QUESTION is PARENT_OF
        for h in headings:
            for q in questions:
                # If question is below heading and in reasonable vertical span
                if q["bbox"][1] > h["bbox"][1] and (q["bbox"][1] - h["bbox"][3]) < 400:
                    pos_pairs.add((h["block_id"], q["block_id"], "PARENT_OF"))

        # Rule 2: QUESTION -> CODE is PARENT_OF
        for q in questions:
            for b in blocks:
                if b["block_type"] == "CODE" and b["bbox"][1] > q["bbox"][1] and (b["bbox"][1] - q["bbox"][3]) < 80:
                    pos_pairs.add((q["block_id"], b["block_id"], "PARENT_OF"))

        # Rule 3: OPTION -> QUESTION is OPTION_OF
        for q in questions:
            for b in blocks:
                if b["block_type"] == "OPTION":
                    # An option belongs to the closest preceding question in the same column
                    if b["bbox"][1] > q["bbox"][1] and (b["bbox"][1] - q["bbox"][3]) < 350:
                        # Check horizontal alignment (same column)
                        overlap_x = max(0.0, min(q["bbox"][2], b["bbox"][2]) - max(q["bbox"][0], b["bbox"][0]))
                        if overlap_x > 50.0:
                            pos_pairs.add((b["block_id"], q["block_id"], "OPTION_OF"))

        # Rule 4: Sibling OPTION -> OPTION sequence is CONTINUATION_OF
        options = [b for b in blocks if b["block_type"] == "OPTION"]
        for i in range(len(options) - 1):
            opt_a = options[i]
            opt_b = options[i + 1]
            if opt_b["bbox"][1] > opt_a["bbox"][1] and (opt_b["bbox"][1] - opt_a["bbox"][3]) < 40:
                overlap_x = max(0.0, min(opt_a["bbox"][2], opt_b["bbox"][2]) - max(opt_a["bbox"][0], opt_b["bbox"][0]))
                if overlap_x > 50.0:
                    pos_pairs.add((opt_a["block_id"], opt_b["block_id"], "CONTINUATION_OF"))

        # Build edge records for positives
        for src_id, tgt_id, rel_label in pos_pairs:
            src_b = block_map[src_id]
            tgt_b = block_map[tgt_id]
            feats = compute_spatial_features(src_b["bbox"], tgt_b["bbox"], page_w, page_h)
            edges.append({
                "doc_id": doc_id,
                "page_id": page_id,
                "source_block_id": src_id,
                "target_block_id": tgt_id,
                "source_text": src_b["text"],
                "target_text": tgt_b["text"],
                "source_role": src_b["block_type"],
                "target_role": tgt_b["block_type"],
                "source_bbox": src_b["bbox"],
                "target_bbox": tgt_b["bbox"],
                "page_width": page_w,
                "page_height": page_h,
                "relationship_label": rel_label,
                "relative_features": feats,
                "annotation_source": "synthetic_procedural",
                "confidence": 1.0,
                "provenance": provenance
            })

        # Negative sampling (NONE)
        pos_id_pairs = {(p[0], p[1]) for p in pos_pairs}
        all_ids = [b["block_id"] for b in blocks]
        neg_candidates = []

        for i in all_ids:
            for j in all_ids:
                if i == j:
                    continue
                if (i, j) in pos_id_pairs or (j, i) in pos_id_pairs:
                    continue

                b_i = block_map[i]
                b_j = block_map[j]
                cx_i = (b_i["bbox"][0] + b_i["bbox"][2]) / 2.0
                cy_i = (b_i["bbox"][1] + b_i["bbox"][3]) / 2.0
                cx_j = (b_j["bbox"][0] + b_j["bbox"][2]) / 2.0
                cy_j = (b_j["bbox"][1] + b_j["bbox"][3]) / 2.0
                dist = math.sqrt(((cx_j - cx_i)/page_w)**2 + ((cy_j - cy_i)/page_h)**2)

                # Collect spatial hard negatives (dist < 0.35)
                if dist < 0.35:
                    neg_candidates.append((dist, i, j))

        neg_candidates.sort(key=lambda x: x[0])
        # Sample balanced ratio ~ 1.5x of positive pairs
        target_negs = int(len(pos_pairs) * 1.5)
        sampled_negs = neg_candidates[:target_negs]

        for dist, src_id, tgt_id in sampled_negs:
            src_b = block_map[src_id]
            tgt_b = block_map[tgt_id]
            feats = compute_spatial_features(src_b["bbox"], tgt_b["bbox"], page_w, page_h)
            edges.append({
                "doc_id": doc_id,
                "page_id": page_id,
                "source_block_id": src_id,
                "target_block_id": tgt_id,
                "source_text": src_b["text"],
                "target_text": tgt_b["text"],
                "source_role": src_b["block_type"],
                "target_role": tgt_b["block_type"],
                "source_bbox": src_b["bbox"],
                "target_bbox": tgt_b["bbox"],
                "page_width": page_w,
                "page_height": page_h,
                "relationship_label": "NONE",
                "relative_features": feats,
                "annotation_source": "synthetic_hard_negative",
                "confidence": 1.0,
                "provenance": provenance
            })

        return edges

    def _wrap_text(self, text: str, font: ImageFont.FreeTypeFont, max_width: int) -> List[str]:
        words = text.split()
        if not words:
            return [""]
        lines = []
        cur_line = []
        dummy_img = Image.new("RGB", (1, 1))
        draw = ImageDraw.Draw(dummy_img)

        for w in words:
            test_line = " ".join(cur_line + [w])
            bbox = draw.textbbox((0, 0), test_line, font=font)
            w_px = bbox[2] - bbox[0]
            if w_px <= max_width:
                cur_line.append(w)
            else:
                if cur_line:
                    lines.append(" ".join(cur_line))
                    cur_line = [w]
                else:
                    lines.append(w)
                    cur_line = []
