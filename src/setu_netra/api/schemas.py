"""
schemas.py: Pydantic schemas and data contracts for SETU-NETRA V2.0.0-RC1.
Complies with RFC 9457 Problem Details for HTTP APIs.
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class TelemetryEvent(BaseModel):
    """Normalized schema for telemetry events traversing the EventBus."""
    event_id: int = Field(..., description="Monotonically increasing event sequence ID")
    correlation_id: str = Field(..., description="Distributed correlation trace ID")
    timestamp_ns: int = Field(..., description="High-resolution timestamp in nanoseconds")
    timestamp_iso: str = Field(..., description="ISO-8601 formatted UTC timestamp")
    event_type: str = Field(..., description="Lifecycle or monitoring event type")
    query_id: Optional[str] = Field(None, description="Query ID if bound to a user query")
    source_subsystem: str = Field(..., description="Originating subsystem or module name")
    payload: Dict[str, Any] = Field(default_factory=dict, description="Event-specific metadata payload")


class ProblemDetails(BaseModel):
    """RFC 9457 Problem Details for HTTP APIs."""
    type: str = Field(default="about:blank", description="URI reference identifying problem type")
    title: str = Field(..., description="Short human-readable summary of the problem")
    status: int = Field(..., description="HTTP status code generated by origin server")
    detail: Optional[str] = Field(None, description="Human-readable explanation specific to this occurrence")
    instance: Optional[str] = Field(None, description="URI reference identifying the specific occurrence")
    correlation_id: Optional[str] = Field(None, description="Correlation ID associated with the error")
    timestamp: str = Field(..., description="ISO-8601 UTC timestamp of error generation")
    code: Optional[str] = Field(None, description="Application-level error code")
    invalid_params: Optional[List[Dict[str, Any]]] = Field(None, description="Validation parameter errors if 422")


class HealthResponse(BaseModel):
    """System health and operational readiness response."""
    status: str = Field(..., description="'HEALTHY', 'DEGRADED', or 'UNHEALTHY'")
    version: str = Field(default="2.0.0-RC1", description="Application version")
    uptime_seconds: float = Field(..., description="Server uptime in seconds")
    database: Dict[str, Any] = Field(default_factory=dict, description="Database connection and persistence status")
    ollama: Dict[str, Any] = Field(default_factory=dict, description="Local Ollama daemon connectivity and model status")
    worker_pool: Dict[str, Any] = Field(default_factory=dict, description="Worker pool states and active capacity")
    hardware: Dict[str, Any] = Field(default_factory=dict, description="Live OS hardware counters (CPU, RAM)")


class QueryRequest(BaseModel):
    """User inquiry execution request."""
    query: str = Field(..., min_length=1, description="Question text")
    doc_id: Optional[str] = Field(None, description="Document ID to scope context")
    model_id: Optional[str] = Field(None, description="Specific requested model ID or 'auto'")
    think: Optional[str] = Field(None, description="'strip', 'keep', or None")
    top_k: int = Field(default=3, ge=1, le=20, description="Top-k passages to retrieve")
    threshold: float = Field(default=0.20, ge=0.0, le=1.0, description="Minimum relevance threshold")


class QueryResponse(BaseModel):
    """Evidence-grounded question answering response."""
    query: str
    answer_text: str
    epistemic_status: str
    citations: List[Any] = Field(default_factory=list)
    grounding_score: float
    executing_model_id: Optional[str] = None
    executing_worker_id: Optional[str] = None
    execution_time_ms: float
    explanation: Optional[str] = None
    thinking: Optional[str] = None
    correlation_id: str
    pipeline_telemetry: Optional[Dict[str, Any]] = None
    domain: Optional[str] = "DOCUMENT_QA"
    reconstructed_question: Optional[str] = None
    verification_method: Optional[str] = None
    step_by_step_explanation: Optional[str] = None
    options: List[Dict[str, str]] = Field(default_factory=list)
    selected_option: Optional[str] = None
    selected_option_text: Optional[str] = None
    option_analysis: Optional[Dict[str, str]] = Field(default_factory=dict)


class ImageQueryResponse(QueryResponse):
    """Image-based question answering response with OCR extraction metadata."""
    extracted_question: str
    ocr_confidence: float
    ocr_detections_count: int
    lifecycle_state: str = "ANSWER_COMPLETED"
    domain: Optional[str] = None
    category: Optional[str] = None
    is_mcq: bool = False
    options: List[Dict[str, str]] = Field(default_factory=list)
    selected_option: Optional[str] = None
    selected_option_text: Optional[str] = None
    step_by_step_explanation: Optional[str] = None
    option_analysis: Dict[str, str] = Field(default_factory=dict)
    sql_clauses: Optional[Dict[str, Any]] = None
    uncertain_spans: List[Dict[str, Any]] = Field(default_factory=list)
    raw_ocr_text: Optional[str] = None


class DocumentPageResponse(BaseModel):
    page_id: str
    doc_id: str
    page_number: int
    width: int
    height: int
    metadata: Dict[str, Any] = Field(default_factory=dict)


class DocumentBlockResponse(BaseModel):
    block_id: int
    page_number: int
    block_type: str
    text: str
    confidence: float
    bounding_box: List[float]
    source_detection_indices: List[int] = Field(default_factory=list)


class PageTextResponse(BaseModel):
    doc_id: str
    page_number: int
    full_text: str
    raw_transcript: str
    blocks_count: int
    ocr_status: str
    detected_questions: List[Dict[str, Any]] = Field(default_factory=list)
    warnings: List[str] = Field(default_factory=list)


class SolvePageQuestionRequest(BaseModel):
    edited_text: Optional[str] = None
    model_id: Optional[str] = None
    think: Optional[bool] = None


class SolveQuestionResponse(BaseModel):
    lifecycle_state: str
    raw_ocr_text: str
    normalized_question: str
    domain: str
    category: str
    is_mcq: bool
    options: List[Dict[str, str]] = Field(default_factory=list)
    selected_option: Optional[str] = None
    selected_option_text: Optional[str] = None
    final_answer: str
    step_by_step_explanation: str
    option_analysis: Dict[str, str] = Field(default_factory=dict)
    sql_clauses: Optional[Dict[str, Any]] = None
    epistemic_status: str
    confidence: float
    model_id: str
    uncertain_spans: List[Dict[str, Any]] = Field(default_factory=list)
    execution_time_ms: float
    warnings: List[str] = Field(default_factory=list)


